"""Generate docs/semantic_vs_keyword.md from the live API (evidence for the report).

Run from the repository root, with the app and the embedding service running:
    embed/.venv/bin/python embed/compare_modes.py

For each query it records the top 5 results in keyword, semantic and hybrid
mode, plus the total keyword matches, and writes a Markdown report.
"""

import os
import sys
from datetime import date
from pathlib import Path

import requests

ROOT = Path(__file__).resolve().parent.parent
BASE = os.environ.get("BASE_URL", "http://localhost:3000")
OUT = ROOT / "docs" / "semantic_vs_keyword.md"
TOP = 5

# Each query is phrased differently from how papers word the topic.
QUERIES = [
    ("teaching machines to understand human language", "The proposal's own example: no paper says this; they say 'natural language processing / understanding'."),
    ("computers that translate between languages", "Everyday words for machine translation."),
    ("figuring out if a review is positive or negative", "A description of sentiment analysis that never uses the term."),
    ("finding names of people and places in text", "Named entity recognition, described in plain words."),
    ("a program that answers questions about a paragraph", "Reading comprehension / extractive question answering."),
    ("making long documents shorter automatically", "Automatic summarisation, without the word 'summarisation'."),
]


def search(q: str, mode: str) -> dict:
    r = requests.get(f"{BASE}/api/search", params={"q": q, "mode": mode}, timeout=30)
    r.raise_for_status()
    return r.json()


def cell(title: str) -> str:
    title = title.replace("|", "\\|")
    return title if len(title) <= 90 else title[:87] + "…"


def main() -> int:
    try:
        requests.get(f"{BASE}/api/stats/overview", timeout=5).raise_for_status()
    except requests.RequestException as err:
        raise SystemExit(f"The app is not reachable at {BASE} ({err}). Start it with: npm --prefix web run dev")

    lines = [
        "# Semantic versus keyword search: examples",
        "",
        f"Generated by `embed/compare_modes.py` against the live API on {date.today().isoformat()}.",
        "Each query describes a topic in everyday words instead of the field's own terms. The table shows the top "
        f"{TOP} results for each search mode.",
        "",
        "- **Keyword** is PostgreSQL full-text search (`websearch_to_tsquery`, `ts_rank_cd`). A paper must contain the query's words, after stemming.",
        "- **Semantic** embeds the query with all-MiniLM-L6-v2 and asks Qdrant for the nearest abstracts by cosine similarity.",
        "- **Hybrid** fuses both rankings with Reciprocal Rank Fusion: score = Σ 1 / (60 + rank).",
        "",
    ]
    summary = ["| # | Query | Keyword matches | Keyword top-1 | Semantic top-1 |", "|---|---|---:|---|---|"]

    for i, (q, why) in enumerate(QUERIES, 1):
        res = {m: search(q, m) for m in ("keyword", "semantic", "hybrid")}
        kw_total = res["keyword"]["total"]
        top1 = lambda m: cell(res[m]["results"][0]["title"]) if res[m]["results"] else "*(none)*"  # noqa: E731
        summary.append(f"| {i} | {q} | {kw_total} | {top1('keyword')} | {top1('semantic')} |")

        lines += [f"## {i}. \"{q}\"", "", f"*Why it is a good test:* {why}", "", f"Keyword matches in total: **{kw_total}**.", ""]
        lines += ["| Rank | Keyword | Semantic (cosine) | Hybrid (RRF) |", "|---:|---|---|---|"]
        for r in range(TOP):
            row = []
            for m in ("keyword", "semantic", "hybrid"):
                items = res[m]["results"]
                if r < len(items):
                    it = items[r]
                    row.append(f"{cell(it['title'])} ({it['year']}) · {it['score']:.3f}")
                else:
                    row.append("–")
            lines.append(f"| {r + 1} | " + " | ".join(row) + " |")
        lines += ["", "**Observation:** _(fill in: which mode found the relevant papers, and why)_", ""]

    lines[9:9] = ["## Summary", "", *summary, ""]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
